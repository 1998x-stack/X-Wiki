#!/usr/bin/env python3
"""Prepare publishable MkDocs content with strict wikilink and privacy guards."""

from __future__ import annotations

import argparse
import shutil
from pathlib import Path

from wiki_links import convert_links
from wiki_lint import lint_wiki

GENERATED_MARKER = ".xwiki-generated"


def reset_output(output: Path, repo: Path) -> None:
    """Refuse to delete any directory that is not known generated output."""
    if output.is_symlink():
        raise ValueError(f"refusing to replace symlink output: {output}")
    resolved = output.resolve()
    repo = repo.resolve()
    default_output = (repo / "sites" / ".site-docs").resolve()
    if resolved == repo or repo.is_relative_to(resolved):
        raise ValueError(f"refusing to replace protected directory: {output}")
    if resolved.is_relative_to(repo) and resolved != default_output:
        raise ValueError(f"refusing to replace protected repository content: {output}")
    if output.exists():
        if not output.is_dir():
            raise ValueError(f"output is not a directory: {output}")
        if (
            resolved != default_output
            and any(output.iterdir())
            and not (output / GENERATED_MARKER).is_file()
        ):
            raise ValueError(f"refusing to replace non-generated output: {output}")
        shutil.rmtree(output)
    output.mkdir(parents=True)
    (output / GENERATED_MARKER).write_text("generated by X-Wiki\n", encoding="utf-8")


def reject_symlink_sources(directory: Path) -> None:
    if directory.is_symlink():
        raise ValueError(f"publishing symlink directory is forbidden: {directory}")
    if directory.exists():
        for path in directory.rglob("*"):
            if path.is_symlink():
                raise ValueError(f"publishing symlink is forbidden: {path}")


def prepare(repo: Path, output: Path, *, strict: bool = False) -> None:
    repo = repo.resolve()
    if strict:
        errors = [f for f in lint_wiki(repo) if f.severity == "error"]
        if errors:
            examples = "; ".join(
                f"{f.path}:{f.line} {f.code}" for f in errors[:8]
            )
            raise ValueError(f"Wiki lint rejected publishing: {examples}")

    for root in (repo / "wiki", repo / "sites" / "assets", repo / "sites" / "content"):
        reject_symlink_sources(root)
    if (repo / "index.md").is_symlink():
        raise ValueError("index.md cannot be a symlink")
    reset_output(output, repo)
    shutil.copy2(repo / "index.md", output / "index.md")
    shutil.copytree(repo / "wiki", output / "wiki")
    assets = repo / "sites" / "assets"
    if assets.is_dir():
        shutil.copytree(assets, output / "sites" / "assets")
    not_found = repo / "sites" / "content" / "404.md"
    if not_found.is_file():
        shutil.copy2(not_found, output / "404.md")
    # Copy only the allowlisted UX-001 static demo files; never mirror
    # arbitrary site content (which might accidentally include raw evidence).
    demo = repo / "sites" / "content" / "demo"
    if demo.exists():
        if not demo.is_dir():
            raise ValueError("UX-001 demo source is not a directory")
        destination = output / "demo"
        destination.mkdir()
        for name in ("index.html", "demo.css", "demo.js"):
            source = demo / name
            if not source.is_file() or source.is_symlink():
                raise ValueError(f"UX-001 demo asset missing or unsafe: {name}")
            shutil.copy2(source, destination / name)
    for path in output.rglob("*.md"):
        converted = convert_links(
            path.read_text(encoding="utf-8"), path, output, strict=strict
        )
        if strict and "raw/voice/" in converted:
            raise ValueError(f"raw evidence pathname leaked into public output: {path}")
        path.write_text(converted, encoding="utf-8")


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--repo", type=Path, default=Path(__file__).resolve().parents[1])
    parser.add_argument("--output", type=Path)
    parser.add_argument("--strict", action="store_true")
    args = parser.parse_args()
    repo = args.repo.expanduser().resolve()
    output = (args.output or repo / "sites" / ".site-docs").expanduser()
    prepare(repo, output, strict=args.strict)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
